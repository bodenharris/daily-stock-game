/**
 * One-off generator for the static green M3 color scheme in `src/routes/layout.css`.
 * Never imported by the app: players get plain CSS, no color code.
 *
 *   npx tsx src/lib/m3/generate-scheme.ts          # rewrite the generated block in layout.css
 *   npx tsx src/lib/m3/generate-scheme.ts --dry    # print it (plus a contrast report) instead
 *
 * Scheme: MCU `SchemeTonalSpot`, spec 2021 (clean on-colors and inverse roles; the 0.4.0 '2025'
 * output gave a near-black light inverse-surface), standard contrast, from SEED.
 * Up / down roles:
 *   up   = the primary family (aliases, written in layout.css by hand).
 *   down = a custom color: CORAL harmonized toward the seed (`Blend.harmonize`, max 15° hue shift),
 *          laid out on its own tonal palette (chroma DOWN_CHROMA) with the M3 custom-color tones
 *          (light 40 / 100 / 90 / 30, dark 80 / 20 / 30 / 90).
 */
import {
	argbFromHex,
	Blend,
	Contrast,
	Hct,
	hexFromArgb,
	MaterialDynamicColors,
	SchemeTonalSpot,
	TonalPalette,
	type DynamicColor
} from '@material/material-color-utilities';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const SEED = '#2E6B3A';
/** Warm coral for "down"; harmonized toward SEED below. */
export const CORAL = '#E8505B';
/** Chroma of the down palette: below the raw coral (72) so Down never shouts louder than Up. */
const DOWN_CHROMA = 56;
const SPEC = '2021' as const;

const ROLES = [
	'primary',
	'on-primary',
	'primary-container',
	'on-primary-container',
	'primary-fixed',
	'primary-fixed-dim',
	'on-primary-fixed',
	'on-primary-fixed-variant',
	'inverse-primary',
	'secondary',
	'on-secondary',
	'secondary-container',
	'on-secondary-container',
	'secondary-fixed',
	'secondary-fixed-dim',
	'on-secondary-fixed',
	'on-secondary-fixed-variant',
	'tertiary',
	'on-tertiary',
	'tertiary-container',
	'on-tertiary-container',
	'tertiary-fixed',
	'tertiary-fixed-dim',
	'on-tertiary-fixed',
	'on-tertiary-fixed-variant',
	'error',
	'on-error',
	'error-container',
	'on-error-container',
	'surface',
	'surface-dim',
	'surface-bright',
	'surface-container-lowest',
	'surface-container-low',
	'surface-container',
	'surface-container-high',
	'surface-container-highest',
	'on-surface',
	'surface-variant',
	'on-surface-variant',
	'outline',
	'outline-variant',
	'inverse-surface',
	'inverse-on-surface',
	'scrim',
	'shadow',
	'surface-tint',
	'background',
	'on-background'
] as const;

type Role = (typeof ROLES)[number];
type ColorMap = Record<string, string>;

const camel = (role: string) => role.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());

function scheme(isDark: boolean): ColorMap {
	const s = new SchemeTonalSpot(Hct.fromInt(argbFromHex(SEED)), isDark, 0, SPEC);
	const mdc = MaterialDynamicColors as unknown as Record<string, DynamicColor>;
	const out: ColorMap = {};
	for (const role of ROLES) out[role] = hexFromArgb(mdc[camel(role)].getArgb(s));
	return out;
}

function downRoles(isDark: boolean): ColorMap {
	const harmonized = Hct.fromInt(Blend.harmonize(argbFromHex(CORAL), argbFromHex(SEED)));
	const palette = TonalPalette.fromHueAndChroma(harmonized.hue, DOWN_CHROMA);
	const [base, on, container, onContainer] = isDark ? [80, 20, 30, 90] : [40, 100, 90, 30];
	return {
		down: hexFromArgb(palette.tone(base)),
		'on-down': hexFromArgb(palette.tone(on)),
		'down-container': hexFromArgb(palette.tone(container)),
		'on-down-container': hexFromArgb(palette.tone(onContainer))
	};
}

function block(selectorComment: string, map: ColorMap, down: ColorMap) {
	const lines = ROLES.map((r: Role) => `\t--md-sys-color-${r}: ${map[r]};`);
	const downLines = Object.entries(down).map(([k, v]) => `\t--md-ext-color-${k}: ${v};`);
	return `${selectorComment} {\n${lines.join('\n')}\n\t/* custom color: down (harmonized coral) */\n${downLines.join('\n')}\n}`;
}

function ratio(a: string, b: string) {
	return Contrast.ratioOfTones(Hct.fromInt(argbFromHex(a)).tone, Hct.fromInt(argbFromHex(b)).tone);
}

const light = scheme(false);
const dark = scheme(true);
const downLight = downRoles(false);
const downDark = downRoles(true);

const header = `/* @generated by src/lib/m3/generate-scheme.ts: seed ${SEED}, SchemeTonalSpot, spec ${SPEC}, contrast 0; down = ${CORAL} harmonized. Do not edit by hand. */`;
// Light on :root; dark via the media query (system preference) and `.dark` for forced subtrees.
const css = [
	header,
	block(':root', light, downLight),
	`@media (prefers-color-scheme: dark) {\n${block(':root', dark, downDark)
		.split('\n')
		.map((l) => `\t${l}`)
		.join('\n')}\n}`,
	block('.dark', dark, downDark),
	block('.light', light, downLight)
].join('\n\n');

const START = '/* @generated:scheme:start */';
const END = '/* @generated:scheme:end */';

if (process.argv.includes('--dry')) {
	console.log(css);
} else {
	const file = fileURLToPath(new URL('../../routes/layout.css', import.meta.url));
	const src = readFileSync(file, 'utf8');
	const a = src.indexOf(START);
	const b = src.indexOf(END);
	if (a < 0 || b < 0) throw new Error(`markers not found in ${file}`);
	writeFileSync(file, `${src.slice(0, a + START.length)}\n${css}\n${src.slice(b)}`);
	console.log(`updated ${file}`);
}

// Contrast report (WCAG ratios from HCT tone; AA = 4.5 text, 3 large text / UI)
const pairs: [string, string][] = [
	['primary', 'on-primary'],
	['primary-container', 'on-primary-container'],
	['secondary-container', 'on-secondary-container'],
	['surface', 'on-surface'],
	['surface', 'on-surface-variant'],
	['surface', 'primary'],
	['surface-container', 'on-surface-variant'],
	['surface', 'outline']
];
for (const [name, map, down] of [
	['light', light, downLight],
	['dark', dark, downDark]
] as const) {
	console.error(`\n${name}`);
	for (const [bg, fg] of pairs)
		console.error(`  ${bg} / ${fg}: ${ratio(map[bg], map[fg]).toFixed(2)}`);
	console.error(`  down / on-down: ${ratio(down.down, down['on-down']).toFixed(2)}`);
	console.error(
		`  down-container / on-down-container: ${ratio(down['down-container'], down['on-down-container']).toFixed(2)}`
	);
	console.error(`  surface / down (text): ${ratio(map.surface, down.down).toFixed(2)}`);
	console.error(
		`  surface-container-low / down: ${ratio(map['surface-container-low'], down.down).toFixed(2)}`
	);
	console.error(
		`  surface-container-low / primary: ${ratio(map['surface-container-low'], map.primary).toFixed(2)}`
	);
	console.error(
		`  key: primary ${map.primary} container ${map['primary-container']} | down ${down.down} container ${down['down-container']} | surface ${map.surface}`
	);
}
